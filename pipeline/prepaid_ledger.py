# ── Accounts that must NOT appear in the prepaid ledger ──────
#
# Prepaid Insurance (135110) and Prepaid Real Estate Taxes (135120) are
# tracked on dedicated analysis tabs in the workpaper — not in this ledger.
# Their monthly amortization JEs are generated by detect_insurance_amortization()
# and detect_retax_amortization() in accrual_entry_generator.py, which credit
# the correct offset accounts (135110 and 135120 respectively).
#
# If these expense accounts appeared in the ledger they would produce wrong JEs
# (CR 135150 Prepaid Other instead of CR 135110 / 135120) and would double-count
# the expense.  Items with these GL account numbers are excluded on load and
# blocked from entering via merge_nexus().
#
# Only items that offset against 135150 Prepaid Other belong here.
_LEDGER_EXCLUDED_GL_ACCOUNTS = {
    '639110',  # Insurance - Property        → handled by detect_insurance_amortization()
    '639120',  # Insurance - General Liability→ handled by detect_insurance_amortization()
    '641110',  # Real Estate Taxes            → handled by detect_retax_amortization()
}


